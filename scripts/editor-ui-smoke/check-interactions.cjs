async page => {
  await page.evaluate(() => { window.files['second.yaml'] = window.files['demo.yaml']; });
  await page.getByRole('button',{name:'打开目录',exact:true}).click();
  await page.getByRole('button',{name:'demo.yaml',exact:true}).click();
  const end = page.getByRole('button',{name:'⇥ done',exact:true});
  await end.scrollIntoViewIfNeeded();
  const endPosition=()=>end.evaluate(el=>({x:parseFloat(el.style.left),y:parseFloat(el.style.top)}));
  const endOrigin=await endPosition();
  const endBox=await end.boundingBox();
  await page.mouse.move(endBox.x+30,endBox.y+18);await page.mouse.down();
  await page.mouse.move(endBox.x-50,endBox.y+98,{steps:8});await page.mouse.up();
  const endMoved=await endPosition();
  if(endMoved.x!==endOrigin.x-80 || endMoved.y!==endOrigin.y+80)throw Error('End marker did not move');
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  if(JSON.stringify(await endPosition())!==JSON.stringify(endOrigin))throw Error('End undo failed');
  await page.getByRole('button',{name:'重做',exact:true}).click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>Object.entries(files).some(([name,text])=>name.endsWith('.json')&&JSON.parse(text).main['return:done']));
  await page.getByRole('button',{name:'打开目录',exact:true}).click();
  await page.getByRole('button',{name:'demo.yaml',exact:true}).click();
  if(JSON.stringify(await endPosition())!==JSON.stringify(endMoved))throw Error('End reload lost position');
  await page.locator('.wf-canvas').evaluate(el=>el.scrollTo(0,0));
  const title = page.getByRole('button', {name:'编辑节点 main',exact:true});
  await title.waitFor({state:'visible'});
  const position = () => title.evaluate(el => ({x:parseFloat(el.parentElement.style.left),y:parseFloat(el.parentElement.style.top)}));
  const origin = await position();
  const box = await title.boundingBox();
  await page.mouse.move(box.x+30,box.y+18); await page.mouse.down();
  await page.mouse.move(box.x+110,box.y+98,{steps:8}); await page.mouse.up();
  const moved=await position();
  if(moved.x!==origin.x+80 || moved.y!==origin.y+80) throw Error('Drag coordinates incorrect '+JSON.stringify({origin,moved}));
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  if(JSON.stringify(await position())!==JSON.stringify(origin))throw Error('One undo must restore whole drag');
  await page.getByRole('button',{name:'重做',exact:true}).click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:'保存',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(()=>Object.keys(window.files).some(name=>name.endsWith('.json')));
  const layouts=await page.evaluate(()=>Object.entries(files).filter(([name])=>name.endsWith('.json')));
  const layout=JSON.parse(layouts[0][1]);
  if(layout.main.main.x!==moved.x || layout.main.main.y!==moved.y)throw Error('Saved layout discarded drag '+JSON.stringify(layout));
  await page.getByRole('button',{name:'打开目录',exact:true}).click();
  await page.getByRole('button',{name:'demo.yaml',exact:true}).click();
  await title.waitFor({state:'visible'});
  if(JSON.stringify(await position())!==JSON.stringify(moved))throw Error('Reload discarded saved coordinates');
  if(await page.locator('.wf-edges path').count()<4)throw Error('Both graph edges must be rendered');
  await title.click();
  if(await page.locator('.wf-selected').count()!==1)throw Error('Click title must select node');
  const role = page.locator('.wf-node-card select').first();
  if(!await role.isDisabled() || await role.inputValue()!=='manager')throw Error('Main start actor must be locked to manager');
  await page.getByRole('button',{name:'编辑节点指令',exact:true}).click();
  const instruction = page.getByRole('dialog',{name:'节点指令',exact:true}).getByRole('textbox');
  const bounds=await instruction.boundingBox();
  if(bounds.width<700 || bounds.height<300)throw Error('Long text editor too small');
  await instruction.fill('取消不应该修改原文');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'编辑节点指令',exact:true}).click();
  if(await instruction.inputValue()==='取消不应该修改原文')throw Error('Cancel leaked buffer');
  await instruction.fill('浏览器冒烟：编辑节点指令并验证 YAML');
  await page.getByRole('button',{name:'确认',exact:true}).click();
  await page.getByRole('button',{name:'应用属性',exact:true}).click();
  await page.getByRole('tab',{name:'YAML',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.wf-preview pre')?.textContent.includes('浏览器冒烟：编辑节点指令并验证 YAML'));
  let confirmed = false;
  page.once('dialog', async dialog => {confirmed = true; await dialog.dismiss();});
  await page.getByRole('button',{name:'second.yaml',exact:true}).click();
  if(!confirmed)throw Error('Dirty file switch must ask for confirmation');
  if(!await page.getByRole('button',{name:'demo.yaml',exact:true}).isDisabled())throw Error('Cancel must retain selected file');
  if(!await page.getByRole('button',{name:'保存',exact:true}).isEnabled())throw Error('Cancel must retain dirty changes');
  await page.getByRole('tab',{name:'节点',exact:true}).click();
  if(await page.getByRole('button',{name:'编辑节点指令',exact:true}).textContent()!=='浏览器冒烟：编辑节点指令并验证 YAML')throw Error('Cancel discarded instruction edit');
  const port=page.locator('.wf-node').filter({has:title}).locator('.wf-port').first();
  await port.click();
  await page.getByRole('button',{name:'⇥ done',exact:true}).click();
  if(await port.textContent()!=='结果done → done')throw Error('Port click did not connect return');
  await page.getByRole('button',{name:'撤销',exact:true}).click();
  if(await port.textContent()!=='结果done → review')throw Error('Undo did not restore original edge');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.waitForFunction(()=>files['demo.yaml'].includes('浏览器冒烟：编辑节点指令并验证 YAML'));
  console.log('PASS drag, undo/redo, save/reopen, node edit/YAML, dirty-switch cancellation, port connect/undo');
}
